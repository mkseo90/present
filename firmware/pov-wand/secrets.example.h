// secrets.h 예시 — **이제는 선택사항이다.** 이 파일이 없어도 펌웨어는 컴파일된다.
//
// 주인 정보(이름·시리얼·LED색)는 소스가 아니라 **기기 플래시에 주입**하는 것을 권장한다:
//
//     python firmware/tools/provision.py "이름" "No.001/001" 00FF66
//
// 그 편이 나은 이유:
//   - 공개 저장소에 사람 실명이 남지 않는다
//   - 새 PC로 옮길 때 이 파일을 들고 다닐 필요가 없다 (보드가 자기 주인을 기억한다)
//   - 보드마다 다른 값(이름·색)이 그 보드 안에 있으므로 헷갈리지 않는다
// 주입값은 LittleFS(/owner)에 남아 재부팅·재플래시 후에도 유지된다.
// 조회는 `provision.py --show`, 삭제는 `provision.py --clear`.
//
// 아래 OWNERS 표는 과거 방식(컴파일 시 MAC→주인 매핑)으로, 호환을 위해 남겨둔다.
// 기기에 주입된 값이 있으면 그것이 우선한다.
#pragma once

// OTA 잠금 해제 PIN — **현재 사용되지 않는다.**
// DFU 명령이 보류되면서(OTA 서비스 미탑재) 펌웨어 어디서도 이 값을 참조하지 않는다.
// OTA를 재도입할 때 되살릴 자리로 남겨둔다. 그때는 길고 추측 어려운 문구로 바꿀 것.
#define DFU_PIN "change-me-to-long-phrase"

// (과거 방식) MAC → 주인 매핑. 부팅 시 시리얼에 찍히는 MAC을 등록한다.
//   예: "MAC: AA:BB:CC:DD:EE:FF"
//
// 전체를 적지 않아도 된다 — 뒷부분만 적으면 그것으로 일치를 판정한다(최소 2글자).
// 콜론 단위로 끊는 것을 권장 (시리얼 출력에서 그대로 잘라 붙일 수 있고 오타가 적다).
//   { "EE:FF",             "이름", "No.001/001", "00FF66" }   // 뒤 2옥텟
//   { "DD:EE:FF",          "이름", "No.001/001", "00FF66" }   // 뒤 3옥텟
//   { "AA:BB:CC:DD:EE:FF", "이름", "No.001/001", "00FF66" }   // 전체
//
// 이름·시리얼에는 공백을 넣지 않는다 (INFO 응답이 공백으로 토큰을 구분하므로).
//
// color: 그 보드에 실제로 달린 LED 색 (RRGGBB 6자리 hex).
//   단색 완드는 펌웨어가 색을 쓰지 않는다(digitalWrite 켜짐/꺼짐뿐). 이 값은
//   INFO로 앱에 전달되어 **앱의 미리보기 색**을 실제 하드웨어와 맞추는 데 쓰인다.
//   예) 초록 00FF66 · 파랑 3399FF · 분홍 FF4FA0 · 노랑 FFD644 · 흰색 FFFFFF
struct Owner { const char* mac; const char* name; const char* serial; const char* color; };
static const Owner OWNERS[] = {
  { "00:00:00:00:00:00", "주인공", "No.001/001", "00FF66" },
};
